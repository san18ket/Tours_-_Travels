/**
 * Tours & Travels — Universal Professional Responsive Table-to-Cards Engine
 * Standardized across all Office and Driver modules
 * 
 * Automatically transforms data tables into responsive modern cards on tablet and mobile (< 992px)
 * while preserving full executive table layouts on desktop (>= 992px).
 * Eliminates all horizontal scrolling across viewports.
 */

(function () {
  'use strict';

  if (typeof window === 'undefined' || typeof document === 'undefined') return;

  const BREAKPOINT_LG = 992;
  const tableKeys = new WeakMap();
  let nextTableKey = 1;

  function getTableKey(table) {
    let key = tableKeys.get(table);
    if (!key) {
      key = table.id || `responsive-table-${nextTableKey++}`;
      tableKeys.set(table, key);
    }
    return key;
  }

  function isNestedTable(table) {
    return !!(table.parentElement && table.parentElement.closest('table'));
  }

  /**
   * Check if a companion server-rendered .cards-grid already exists for this table
   */
  function hasServerRenderedCards(table) {
    const parent = table.closest('section, .bookings-page-view, .finance-page-view, .vg-card, .table-card') || table.parentElement;
    if (!parent) return false;

    // Look for an existing cards-grid that was rendered by server (not generated by this script)
    const existing = parent.querySelector('.cards-grid:not([data-for-table])');
    if (existing && existing.children.length > 0) {
      return true;
    }
    return false;
  }

  function removeResponsiveCards(table) {
    const tableKey = tableKeys.get(table);
    if (!tableKey) return;

    const container = table.closest('.modern-table-container, .table-responsive') || table.parentElement;
    if (!container || !container.parentElement) return;

    const cardsGrid = Array.from(container.parentElement.querySelectorAll('.cards-grid'))
      .find(grid => grid.getAttribute('data-for-table') === tableKey);

    if (cardsGrid) {
      cardsGrid.remove();
    }
    table.removeAttribute('data-cards-generated');
  }

  /**
   * Helper: extract clean text label from a TH element
   */
  function getHeaderLabel(th, index) {
    if (!th) return 'Column ' + (index + 1);

    const explicitLabel = th.getAttribute('data-label') || th.getAttribute('data-column');
    if (explicitLabel) return explicitLabel.trim();

    const clone = th.cloneNode(true);
    clone.querySelectorAll('.d-none, .visually-hidden, .sorting-icon, script, style').forEach(el => el.remove());

    let text = clone.textContent.replace(/\s+/g, ' ').trim();
    if (!text && th.querySelector('i')) {
      const iconClass = th.querySelector('i').className;
      if (iconClass.includes('user')) text = 'User';
      else if (iconClass.includes('calendar')) text = 'Date';
      else if (iconClass.includes('tag')) text = 'Category';
      else if (iconClass.includes('money') || iconClass.includes('dollar') || iconClass.includes('rupee')) text = 'Amount';
      else if (iconClass.includes('car')) text = 'Vehicle';
    }

    return text || 'Column ' + (index + 1);
  }

  /**
   * Helper: extract icon class from TH or infer from label (Tours & Travels domain)
   */
  function getHeaderIcon(th, label) {
    if (!th) return null;
    const icon = th.querySelector('i');
    if (icon) return icon.className;

    const l = (label || '').toLowerCase();
    if (l.includes('name') || l.includes('client') || l.includes('customer') || l.includes('passenger') || l.includes('driver') || l.includes('chauffeur') || l.includes('staff') || l.includes('employee') || l.includes('user') || l.includes('profile')) return 'fa-solid fa-user';
    if (l.includes('vehicle') || l.includes('car') || l.includes('fleet') || l.includes('model') || l.includes('plate')) return 'fa-solid fa-car';
    if (l.includes('route') || l.includes('address') || l.includes('pickup') || l.includes('drop') || l.includes('location') || l.includes('city')) return 'fa-solid fa-location-dot';
    if (l.includes('amount') || l.includes('price') || l.includes('fare') || l.includes('paid') || l.includes('balance') || l.includes('due') || l.includes('salary') || l.includes('cost') || l.includes('disbursed') || l.includes('advance')) return 'fa-solid fa-indian-rupee-sign';
    if (l.includes('date') || l.includes('time') || l.includes('period') || l.includes('month') || l.includes('year') || l.includes('created')) return 'fa-regular fa-calendar-days';
    if (l.includes('phone') || l.includes('mobile') || l.includes('contact')) return 'fa-solid fa-phone';
    if (l.includes('email') || l.includes('mail')) return 'fa-regular fa-envelope';
    if (l.includes('booking') || l.includes('ticket') || l.includes('reservation')) return 'fa-solid fa-ticket';
    if (l.includes('invoice') || l.includes('bill') || l.includes('voucher') || l.includes('receipt')) return 'fa-solid fa-file-invoice-dollar';
    if (l.includes('tour') || l.includes('package')) return 'fa-solid fa-earth-americas';
    if (l.includes('account') || l.includes('bank') || l.includes('vault')) return 'fa-solid fa-building-columns';
    if (l.includes('status') || l.includes('condition')) return 'fa-solid fa-circle-check';
    if (l.includes('dispatch') || l.includes('trip')) return 'fa-solid fa-route';
    if (l.includes('license') || l.includes('badge') || l.includes('code') || l.includes('ref')) return 'fa-solid fa-id-card';

    return null;
  }

  /**
   * Inspect column headers and determine functional roles
   */
  function analyzeColumns(table) {
    const thead = table.querySelector('thead');
    const headerRow = thead ? thead.querySelector('tr') : table.querySelector('tr');
    if (!headerRow) return [];

    const ths = Array.from(headerRow.querySelectorAll('th, td'));
    const totalCols = ths.length;

    return ths.map((th, index) => {
      const rawText = (th.textContent || '').trim().toLowerCase();
      const label = getHeaderLabel(th, index);
      const icon = getHeaderIcon(th, label);
      const explicitPriority = th.getAttribute('data-column-priority') || th.getAttribute('data-priority');

      const isIndex = (index === 0 && (rawText === '#' || rawText === 'no' || rawText === 'sr' || rawText === 'sr.' || rawText === 'no.' || rawText === 'sr no' || th.querySelector('input[type="checkbox"]')));
      const firstDataRow = table.querySelector('tbody tr');
      const firstRowCell = firstDataRow && firstDataRow.children[index];
      const hasActionControls = !!(firstRowCell && firstRowCell.querySelector('button, a.btn, a.action-btn-table, form, .dropdown, [data-bs-toggle="dropdown"], .action-dots-btn'));
      const isAction = rawText.includes('action') ||
        rawText.includes('manage') ||
        rawText.includes('option') ||
        rawText.includes('operation') ||
        (index === totalCols - 1 && !rawText && hasActionControls);

      const isStatus = (rawText.includes('status') || rawText.includes('state') || rawText.includes('active') || rawText.includes('verified'));
      const isPrimary = explicitPriority === 'primary' || (!isIndex && !isAction && !isStatus && (
        rawText.includes('name') ||
        rawText.includes('client') ||
        rawText.includes('customer') ||
        rawText.includes('driver') ||
        rawText.includes('employee') ||
        rawText.includes('passenger') ||
        rawText.includes('booking') ||
        rawText.includes('dispatch') ||
        rawText.includes('trip') ||
        rawText.includes('tour') ||
        rawText.includes('vehicle') ||
        rawText.includes('invoice') ||
        rawText.includes('account') ||
        rawText.includes('title') ||
        index === (isIndex ? 1 : 0)
      ));

      return {
        index,
        th,
        label,
        icon,
        isIndex,
        isAction,
        isStatus,
        isPrimary,
        priority: explicitPriority || (isPrimary || isStatus || isAction ? 'primary' : 'secondary')
      };
    });
  }

  /**
   * Convert table rows to modern cards
   */
  function convertTableToCards(table) {
    if (isNestedTable(table)) return;

    // On desktop, remove auto-generated cards and let native table display
    if (window.innerWidth >= BREAKPOINT_LG) {
      removeResponsiveCards(table);
      return;
    }

    // Skip if page already has custom server-rendered companion cards
    if (hasServerRenderedCards(table)) {
      return;
    }

    // Skip excluded tables (print view, calendar, modal dialogs)
    if (table.closest('#printContainer, .print-view, .modal, .no-card-convert') ||
        table.classList.contains('no-card-convert') ||
        table.classList.contains('calendar-table') ||
        table.getAttribute('data-responsive') === 'none') {
      return;
    }

    // Preserve tables with interactive form input fields (prevent detaching user inputs)
    if (table.querySelector('tbody input[name], tbody select[name], tbody textarea[name]')) {
      return;
    }

    const tbody = table.querySelector('tbody');
    const tableKey = getTableKey(table);

    const container = table.closest('.modern-table-container, .table-responsive') || table.parentElement;
    if (!container) return;

    // Find or create companion .cards-grid
    let cardsGrid = Array.from(container.parentElement.querySelectorAll('.cards-grid'))
      .find(grid => grid.getAttribute('data-for-table') === tableKey);

    if (!cardsGrid) {
      cardsGrid = document.createElement('div');
      cardsGrid.className = 'cards-grid';
      cardsGrid.setAttribute('data-for-table', tableKey);
      cardsGrid.style.cssText = 'display: grid; gap: 16px; margin-bottom: 24px;';
      container.parentNode.insertBefore(cardsGrid, container.nextSibling);
    }

    const columns = analyzeColumns(table);
    const rows = Array.from(tbody.querySelectorAll('tr'));

    // Handle empty table state
    if (rows.length === 0 || (rows.length === 1 && rows[0].querySelector('td[colspan]'))) {
      const emptyTd = rows.length ? rows[0].querySelector('td[colspan]') : null;
      let emptyText = emptyTd ? emptyTd.innerText.trim() : 'No records found.';
      if (emptyText.length > 150) emptyText = 'No records found matching your query.';

      const emptyCard = document.createElement('div');
      emptyCard.className = 'no-data-message modern-card';
      emptyCard.style.cssText = 'grid-column: 1 / -1; text-align: center; padding: 2.5rem 1rem;';
      emptyCard.innerHTML = `
        <div class="no-data-icon"><i class="fa-regular fa-folder-open"></i></div>
        <h4 style="font-weight: 700; color: #1e293b; margin-bottom: 6px;">No Records Found</h4>
        <p class="text-muted" style="margin: 0; font-size: 0.85rem;">${emptyText}</p>
      `;
      cardsGrid.replaceChildren(emptyCard);
      return;
    }

    // Rebuild cards
    cardsGrid.innerHTML = '';

    const primaryCol = columns.find(c => c.isPrimary) || columns.find(c => !c.isIndex && !c.isAction) || columns[0];
    const statusCol = columns.find(c => c.isStatus);
    const actionCol = columns.find(c => c.isAction);

    rows.forEach((row, rowIndex) => {
      if (row.querySelector('td[colspan]')) return; // Skip colspan headers/subtotals

      const cells = Array.from(row.querySelectorAll('td'));
      if (cells.length === 0) return;

      const card = document.createElement('div');
      card.className = 'modern-card';
      card.setAttribute('data-row-index', rowIndex);

      // Mirror row attributes (ID, data-*)
      Array.from(row.attributes).forEach(attr => {
        if (attr.name.startsWith('data-') || attr.name === 'id') {
          card.setAttribute(attr.name === 'id' ? 'data-target-row-id' : attr.name, attr.value);
        }
      });

      // Synchronize visibility if row was filtered out
      if (row.style.display === 'none' || row.classList.contains('d-none')) {
        card.style.display = 'none';
      }

      // 1. CARD TOP (Title/Primary Details on left + Status Badge on right)
      const cardHeader = document.createElement('div');
      cardHeader.className = 'card-header';
      cardHeader.style.cssText = 'display: flex; justify-content: space-between; align-items: flex-start; gap: 10px; margin-bottom: 12px;';

      const titleWrap = document.createElement('div');
      titleWrap.className = 'card-title-wrap';
      titleWrap.style.cssText = 'flex: 1; min-width: 0;';

      const primaryCell = primaryCol ? cells[primaryCol.index] : cells[0];
      if (primaryCell) {
        const pClone = primaryCell.cloneNode(true);
        pClone.querySelectorAll('.dropdown, .action-dots-btn, .table-action-buttons').forEach(el => el.remove());
        const titleH5 = document.createElement('div');
        titleH5.className = 'card-title';
        titleH5.style.cssText = 'font-size: 0.98rem; font-weight: 700; color: var(--vg-navy-900, #0F172A); line-height: 1.35;';
        titleH5.innerHTML = pClone.innerHTML;
        titleWrap.appendChild(titleH5);
      } else {
        const titleH5 = document.createElement('div');
        titleH5.className = 'card-title';
        titleH5.textContent = 'Record #' + (rowIndex + 1);
        titleWrap.appendChild(titleH5);
      }
      cardHeader.appendChild(titleWrap);

      if (statusCol && cells[statusCol.index]) {
        const statusCell = cells[statusCol.index];
        const statusWrap = document.createElement('div');
        statusWrap.className = 'card-header-status';
        statusWrap.style.cssText = 'flex-shrink: 0;';
        statusWrap.innerHTML = statusCell.innerHTML;
        cardHeader.appendChild(statusWrap);
      }

      card.appendChild(cardHeader);

      // 2. CARD DETAILS (Key-Value metadata list)
      const cardDetails = document.createElement('div');
      cardDetails.className = 'card-details';
      cardDetails.style.cssText = 'display: flex; flex-direction: column; gap: 6px; margin-bottom: 14px;';

      columns.forEach(col => {
        if (col.isIndex) return;
        if (primaryCol && col.index === primaryCol.index) return;
        if (statusCol && col.index === statusCol.index) return;
        if (actionCol && col.index === actionCol.index) return;

        const cell = cells[col.index];
        if (!cell) return;

        const cellText = cell.textContent.trim();
        if (!cellText && !cell.querySelector('img, i, span, badge, a, button')) return;

        const detailItem = document.createElement('div');
        detailItem.className = 'detail-item';
        detailItem.style.cssText = 'display: flex; justify-content: space-between; align-items: center; gap: 8px; font-size: 0.82rem; padding: 4px 0; border-bottom: 1px solid #F1F5F9;';

        const keySpan = document.createElement('span');
        keySpan.className = 'detail-item-key';
        keySpan.style.cssText = 'color: #64748B; font-size: 0.78rem; font-weight: 600; text-transform: uppercase; letter-spacing: 0.4px; flex-shrink: 0; display: flex; align-items: center; gap: 5px;';
        const iconHtml = col.icon ? `<i class="${col.icon}" style="color: var(--brand-primary, #176B5B); width: 14px; text-align: center;"></i>` : '';
        keySpan.innerHTML = `${iconHtml}<span>${col.label}</span>`;

        const valSpan = document.createElement('span');
        valSpan.className = 'detail-item-val';
        valSpan.style.cssText = 'color: #0F172A; font-weight: 600; text-align: right; word-break: break-word;';
        valSpan.innerHTML = cell.innerHTML;

        detailItem.appendChild(keySpan);
        detailItem.appendChild(valSpan);
        cardDetails.appendChild(detailItem);
      });

      card.appendChild(cardDetails);

      // 3. CARD ACTIONS (Tap-friendly action buttons)
      if (actionCol && cells[actionCol.index]) {
        const actionCell = cells[actionCol.index];
        const actionHtml = actionCell.innerHTML.trim();

        if (actionHtml) {
          const cardActions = document.createElement('div');
          cardActions.className = 'card-actions';

          const actionWrap = document.createElement('div');
          actionWrap.className = 'card-action-wrapper';
          actionWrap.innerHTML = actionHtml;

          // Wire up click event listeners to proxy back to original table buttons if needed
          actionWrap.querySelectorAll('button, a, .action-btn-table, .btn').forEach(btn => {
            const hasBsToggle = btn.hasAttribute('data-bs-toggle') || btn.hasAttribute('data-bs-target');
            const hasInlineClick = btn.getAttribute('onclick');
            if (!hasBsToggle && !hasInlineClick) {
              const matchingSelector = btn.className.split(' ').filter(c => c && !c.includes(':')).map(c => '.' + c).join('');
              const origBtn = matchingSelector ? actionCell.querySelector(matchingSelector) : null;
              if (origBtn && origBtn !== btn) {
                btn.addEventListener('click', function (e) {
                  const href = btn.getAttribute('href');
                  if (!href || href === '#' || href.startsWith('javascript:')) {
                    e.preventDefault();
                    origBtn.click();
                  }
                });
              }
            }
          });

          cardActions.appendChild(actionWrap);
          card.appendChild(cardActions);
        }
      }

      cardsGrid.appendChild(card);
    });

    table.setAttribute('data-cards-generated', 'true');
  }

  /**
   * Observe table mutations for live search filtering or AJAX updates
   */
  function observeTableChanges(table) {
    if (table._cardsObserverAttached) return;
    table._cardsObserverAttached = true;

    const tbody = table.querySelector('tbody');
    if (!tbody) return;

    let debounceTimer;
    const observer = new MutationObserver(function (mutations) {
      clearTimeout(debounceTimer);
      const isOnlyAttr = mutations.length > 0 && mutations.every(m => m.type === 'attributes');
      if (isOnlyAttr) {
        const container = table.closest('.modern-table-container, .table-responsive') || table.parentElement;
        const tableKey = getTableKey(table);
        const cardsGrid = container && container.parentElement
          ? Array.from(container.parentElement.querySelectorAll('.cards-grid')).find(g => g.getAttribute('data-for-table') === tableKey)
          : null;

        if (cardsGrid) {
          const rows = Array.from(tbody.querySelectorAll('tr'));
          rows.forEach((row, i) => {
            const card = cardsGrid.querySelector(`.modern-card[data-row-index="${i}"]`);
            if (card) {
              card.style.display = (row.style.display === 'none' || row.classList.contains('d-none')) ? 'none' : '';
            }
          });
          return;
        }
      }

      debounceTimer = setTimeout(function () {
        convertTableToCards(table);
      }, 100);
    });

    observer.observe(tbody, {
      childList: true,
      subtree: true,
      attributes: true,
      attributeFilter: ['style', 'class']
    });
  }

  /**
   * Universal scan: discover and adapt all data tables
   */
  function initAllTableCards() {
    const selector = 'table.modern-table, .modern-table-container > table, .table-responsive > table:not(.no-card-convert)';
    document.querySelectorAll(selector).forEach(table => {
      convertTableToCards(table);
      if (window.innerWidth < BREAKPOINT_LG && !isNestedTable(table)) {
        observeTableChanges(table);
      }
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initAllTableCards);
  } else {
    initAllTableCards();
  }

  let resizeTimer;
  window.addEventListener('resize', function () {
    clearTimeout(resizeTimer);
    resizeTimer = setTimeout(initAllTableCards, 200);
  });

  window.refreshResponsiveTableCards = initAllTableCards;

})();
